package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"sort"
	"testing"
)

// A finding in a file whose header marks it as generated is left out, unless
// --no-repo-config says not to take the scanned repository's word for anything.
func TestRun_FindingsInGeneratedFilesAreLeftOut(t *testing.T) {
	cfg, target, vault := fakeScanFixture(t)
	gen := "# @generated by a code generator; do not edit\nimport os\nos.system(cmd)\n"
	if err := os.WriteFile(filepath.Join(target, "gen.py"), []byte(gen), 0o644); err != nil {
		t.Fatal(err)
	}
	files := func(extra ...string) []string {
		t.Helper()
		out := filepath.Join(t.TempDir(), "report.json")
		args := append([]string{"--config", cfg, "--vault", vault, "--fail-on", "", "--json-report", out}, extra...)
		if err := run(append(args, target)); err != nil {
			t.Fatal(err)
		}
		b, err := os.ReadFile(out)
		if err != nil {
			t.Fatal(err)
		}
		var rep struct {
			Findings []struct {
				Location struct {
					File string `json:"file"`
				} `json:"location"`
			} `json:"findings"`
		}
		if err := json.Unmarshal(b, &rep); err != nil {
			t.Fatal(err)
		}
		var fs []string
		for _, f := range rep.Findings {
			fs = append(fs, f.Location.File)
		}
		sort.Strings(fs)
		return fs
	}
	if got := files(); len(got) != 1 || got[0] != "app.py" {
		t.Errorf("findings in %v, want only app.py (gen.py is marked generated)", got)
	}
	if got := files("--no-repo-config"); len(got) != 2 {
		t.Errorf("--no-repo-config: findings in %v, want app.py and gen.py", got)
	}
	if got := files("--no-default-excludes"); len(got) != 2 {
		t.Errorf("--no-default-excludes: findings in %v, want app.py and gen.py", got)
	}
}
