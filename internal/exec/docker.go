package exec

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	osexec "os/exec"
	"path"
	"time"
)

// DockerRunner runs the tool inside a pinned container image. Each mount is
// bind-mounted under /mnt/<name>; placeholders resolve to those container
// paths. This is the production execution model (reproducible, isolated).
type DockerRunner struct {
	// Image is the container reference. Pin to a digest in production.
	Image string
	// Network sets --network (e.g. "none" to deny egress during a scan).
	// Empty leaves Docker's default.
	Network string
	// Unconfined turns the hardening flags off (see hardeningArgs). It exists as
	// an escape hatch for an image that turns out to need a capability.
	Unconfined bool
}

// hardeningArgs are the `docker run` flags every tool container gets.
//
// A scanner container processes a repository that may be hostile, and some tools
// run code from it: Psalm loads plugins named in the repository's psalm.xml, a
// .NET restore runs MSBuild targets, govulncheck drives the Go toolchain. The
// defaults Docker gives a container are more than a scanner needs, so:
//
//   - no-new-privileges: a setuid binary cannot raise privileges.
//   - cap-drop ALL: no raw sockets, no mknod, no chroot, no chown, no setuid, none
//     of the default capability set. One is added back, DAC_OVERRIDE: the tools run
//     as the image's user (usually root), and the report directory and the source
//     tree are bind mounts owned by the invoking user. Without it container root
//     is just "other" to those files: it could not write its report, and would
//     silently skip source files that are not world-readable.
//   - pids-limit: a fork bomb in a build script stops at the container.
//
// What this does not do: run as a non-root user or with a read-only root
// filesystem. Both would be better, and both break images that install their tool
// under root's home or write caches to their own filesystem. Memory is not capped
// either: the right limit depends on the repository.
var hardeningArgs = []string{
	"--security-opt", "no-new-privileges",
	"--cap-drop", "ALL",
	"--cap-add", "DAC_OVERRIDE",
	"--pids-limit", "4096",
}

func (r DockerRunner) Run(ctx context.Context, c Command) (Result, error) {
	// The container is named so it can be killed. Killing the `docker run` client
	// does not stop the container: it would keep scanning (and keep its mounts
	// busy) after a timeout or Ctrl-C, with nothing left to collect the result.
	name := containerName()
	args, err := r.runArgs(c, name)
	if err != nil {
		return Result{}, err
	}
	return runCmd(ctx, "docker", args, runOpts{onCancel: func() { killContainer(name) }})
}

// runArgs builds the `docker run` argument list for one tool invocation.
func (r DockerRunner) runArgs(c Command, name string) ([]string, error) {
	containerPath := func(name string) string { return path.Join("/mnt", name) }

	image := c.Image
	if image == "" {
		image = r.Image
	}

	if image == "" {
		// `docker run` with no image fails with "invalid reference format", which
		// says nothing about which tool or why.
		return nil, fmt.Errorf("no container image is configured for this tool, so it cannot run under --runner docker")
	}

	// Per-command network overrides the runner default. "default" means Docker's
	// normal bridge (no flag); "none"/named are passed through as --network.
	network := c.Network
	if network == "" {
		network = r.Network
	}

	args := []string{"run", "--rm", "--name", name}
	if !r.Unconfined {
		args = append(args, hardeningArgs...)
	}
	if network != "" && network != "default" {
		args = append(args, "--network", network)
	}
	for _, m := range c.Mounts {
		spec := m.HostPath + ":" + containerPath(m.Name)
		if m.ReadOnly {
			spec += ":ro"
		}
		args = append(args, "-v", spec)
	}
	args = append(args, image)
	// Note: c.Bin is deliberately NOT passed in docker mode — scanner images set
	// the tool as their ENTRYPOINT, so passing the binary again would double it
	// (e.g. `gosec gosec ...`). c.Bin is used only by the local runner.
	args = append(args, resolveArgs(c.Args, containerPath, mountNames(c.Mounts))...)
	return args, nil
}

// containerName returns a unique name for one tool container.
func containerName() string {
	var b [6]byte
	if _, err := rand.Read(b[:]); err != nil {
		return fmt.Sprintf("achilles-%d-%d", os.Getpid(), time.Now().UnixNano())
	}
	return "achilles-" + hex.EncodeToString(b[:])
}

// killContainer stops a tool container by name. It runs on its own short clock:
// the context that would normally bound it is the one that just ended. Errors are
// ignored: the container may already be gone, which is the outcome we want.
func killContainer(name string) {
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	_ = osexec.CommandContext(ctx, "docker", "kill", name).Run() // #nosec G204 -- fixed binary; name is generated by containerName
}
