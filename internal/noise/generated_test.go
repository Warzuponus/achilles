func TestIsGenerated(t *testing.T) {
	license := strings.Repeat("// Copyright 2026 The Authors. Licensed under the Apache License.\n", 12)
	for _, c := range []struct {
		name, src string
		want      bool
	}{
		{"go marker", "// Code generated by stringer -type=Kind; DO NOT EDIT.\n\npackage expr\n", true},
		{"go marker after a licence", license + "\n// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n", true},
		{"go marker after the package clause", "package expr\n\n// Code generated by hand. DO NOT EDIT.\n", false},
		{"not quite the marker", "// Code generated by stringer; do not edit\npackage expr\n", false},
		{"@generated in a comment", "/**\n * @generated SignedSource<<abc>>\n */\nexport const x = 1;\n", true},
		{"@generated in a hash comment", "# @generated by pip-compile\nrequests==2.32.0\n", true},
		{"@generated in code, not a comment", "const note = \"@generated\";\n", false},
		{"@generated far down", strings.Repeat("x = 1\n", 20) + "// @generated\n", false},
		{"hand-written", "package main\n\nfunc main() {}\n", false},
		{"empty", "", false},
	} {
		if got := IsGenerated(strings.NewReader(c.src)); got != c.want {
			t.Errorf("%s: IsGenerated = %v, want %v", c.name, got, c.want)
		}
	}
}

func TestGenerated_DropsFindingsInGeneratedFilesButNotWhatMustStay(t *testing.T) {
	root := t.TempDir()
	write := func(name, body string) {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("pkg/kind_string.go", "// Code generated by stringer -type=Kind; DO NOT EDIT.\n\npackage pkg\n")
	write("pkg/kind.go", "package pkg\n")
	at := func(tool, rule, file string) model.Finding {
		return model.Finding{Tool: tool, RuleID: rule, Location: model.Location{File: file}}
	}
	secret := at("gitleaks", "generic-api-key", "pkg/kind_string.go")
	advisory := at("osv-scanner", "GHSA-xxxx-xxxx-xxxx", "pkg/kind_string.go")
	history := at("gitleaks", "G101", "pkg/kind_string.go")
	history.Commit = "abc123"
	findings := []model.Finding{
		at("gosec", "G104", "pkg/kind_string.go"), // generated: dropped
		at("gosec", "G104", "pkg/kind.go"),        // hand-written: kept
		secret, advisory, history,                 // never dropped on the header's word
		at("gosec", "G104", "../outside/x.go"), // outside the root: kept, not read
		at("gosec", "G104", "pkg/missing.go"),  // unreadable: kept
	}
	kept, excluded := Generated(root, findings)
	if len(excluded) != 1 || excluded[0].Location.File != "pkg/kind_string.go" || excluded[0].Tool != "gosec" {
		t.Fatalf("excluded = %+v, want only the gosec finding in the generated file", excluded)
	}
	if len(kept) != len(findings)-1 {
		t.Errorf("kept %d of %d", len(kept), len(findings))
	}
}
