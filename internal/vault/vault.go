// Package vault implements the Evidence Vault (DESIGN.md §5.1): an append-only,
// provenance store of everything a scan produces — raw tool output, normalized
// findings, LLM prompts/responses, verdicts, and human feedback. It is the
// audit trail, the reproducibility record, and the learning corpus, all at once.
//
// Immutability is structural: the Store exposes no update or delete. A
// correction is a new record that references the one it supersedes (PrevID).
//
// There are two backends behind the Store interface: a JSONL file (the default)
// and PostgreSQL.
package vault

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"time"
)

// Kind classifies a record.
type Kind string

const (
	KindScanMeta    Kind = "scan_meta"
	KindRawOutput   Kind = "raw_output"
	KindFinding     Kind = "finding"
	KindLLMCall     Kind = "llm_call"
	KindVerdict     Kind = "verdict"
	KindRemediation Kind = "remediation"
	KindFeedback    Kind = "feedback"
	KindGenRule     Kind = "generated_rule"
	KindTenant      Kind = "tenant"       // SaaS tenant-registry record (latest-wins by RunID=tenant id)
	KindSBOM        Kind = "sbom"         // software bill of materials (CycloneDX) generated by --sbom
	KindReview      Kind = "review"       // holistic full-repo security review (--review)
	KindAdvisory    Kind = "advisory"     // SCA dependency-upgrade advice (--sca-advice)
	KindThreatModel Kind = "threat_model" // OTM threat model (--threat-model)
)

// Record is one immutable entry.
type Record struct {
	ID            string          `json:"id"`
	RunID         string          `json:"runId"`
	Phase         string          `json:"phase,omitempty"`
	Kind          Kind            `json:"kind"`
	Source        string          `json:"source,omitempty"`        // tool or model id
	PromptVersion string          `json:"promptVersion,omitempty"` // for LLM records
	Fingerprint   string          `json:"fingerprint,omitempty"`   // links records about the same finding
	PrevID        string          `json:"prevId,omitempty"`        // record this supersedes/corrects
	Timestamp     time.Time       `json:"ts"`
	Payload       json.RawMessage `json:"payload,omitempty"`
}

// Store is the append-only Evidence Vault contract. Note the absence of any
// Update/Delete — that is the immutability guarantee.
type Store interface {
	// Append stores r, assigning ID and Timestamp, and returns the stored copy.
	Append(r Record) (Record, error)
	// Get returns a record by ID.
	Get(id string) (Record, bool)
	// ByRun returns all records for a run, in insertion order.
	ByRun(runID string) []Record
	// ByFingerprint returns all records for a finding fingerprint, in order.
	ByFingerprint(fp string) []Record
	// All returns every record in insertion order (the learning corpus).
	All() []Record
}

// Purger is implemented by stores that support retention: time-based expiry of
// records older than a cutoff. It is deliberately NOT part of Store — the base
// contract is append-only and tamper-evident. Retention is a coarse, admin-gated
// policy operation (SaaS cost/compliance), distinct from record mutation.
type Purger interface {
	// Purge deletes records with Timestamp before the cutoff and returns the count.
	Purge(before time.Time) (int, error)
}

// computeID is content+sequence addressed so identical payloads at different
// points in a run still get distinct, stable IDs.
func computeID(r Record, seq int) string {
	h := sha256.New()
	enc := json.NewEncoder(h)
	_ = enc.Encode(struct {
		Record
		Seq int
	}{r, seq})
	return hex.EncodeToString(h.Sum(nil))[:24]
}
